// Builds the browser side of the new system: server/client/storage.ts (and
// the server/lib modules it uses) into frontend/js/00-server-storage.js, one
// readable script the legacy page loads before its own scripts.
//
//   node tools/build-client.mjs          write it
//   node tools/build-client.mjs --check  fail if the committed file is not what the source builds
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = new URL('../frontend/js/00-server-storage.js', import.meta.url);
const result = await build({
  entryPoints: [new URL('../server/client/storage.ts', import.meta.url).pathname],
  bundle: true, format: 'iife', target: 'es2020', write: false, charset: 'utf8', legalComments: 'none',
  banner: { js: '// Generated by tools/build-client.mjs from server/client/storage.ts. Do not edit; change the source and rebuild.' },
});
const text = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(OUT, 'utf8'); } catch {}
  if (now !== text) { console.error('frontend/js/00-server-storage.js is out of date: run node tools/build-client.mjs'); process.exit(1); }
  console.log('OK: frontend/js/00-server-storage.js matches its source');
} else {
  writeFileSync(OUT, text);
  console.log(`frontend/js/00-server-storage.js: ${Buffer.byteLength(text)} bytes`);
}
