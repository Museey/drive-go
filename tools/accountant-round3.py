def rowh(texts, widths):
    vis = lambda p: sum(1 for ch in p if not ('\u0e31' <= ch <= '\u0e3a' or '\u0e47' <= ch <= '\u0e4e' or ch == '\u0e34'))
    lines = 1
    for t, w in zip(texts, widths):
        per = max(1, int((w - 2) * 1.25))
        lines = max(lines, sum(max(1, -(-vis(p) // per)) for p in str(t or '').split('\n')))
    return min(409, 15 * lines + 6)

