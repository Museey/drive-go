def rowh(texts, widths):
    vis = lambda p: sum(1 for ch in p if not ('ั' <= ch <= 'ฺ' or '็' <= ch <= '๎' or ch == 'ิ'))
    lines = 1
    for t, w in zip(texts, widths):
        per = max(1, int((w - 2) * 1.25))
        lines = max(lines, sum(max(1, -(-vis(p) // per)) for p in str(t or '').split('\n')))
    return min(409, 15 * lines + 6)

def table(ws, title, heads, widths):
    ws.cell(1, 1, title).font = Font(name=F, bold=True, size=12)
    for i, (h, w) in enumerate(zip(heads, widths), 1):
        c = ws.cell(2, i, h); c.font = Font(name=F, bold=True, color='FFFFFF'); c.fill = hdr; c.alignment = Alignment(wrap_text=True, vertical='center'); c.border = box
        ws.column_dimensions[c.column_letter].width = w
    ws.freeze_panes = 'C3'; ws.page_setup.orientation = 'landscape'; ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth = 1; ws.page_setup.fitToHeight = 0; ws.sheet_properties.pageSetUpPr.fitToPage = True
